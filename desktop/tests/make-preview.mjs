// Builds `dist/preview.html` from the real `dist/index.html`, so the page that is looked at is
// the page that ships — a hand-copied one drifts, and a missing element takes the whole script
// down with it.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const markup = readFileSync(join(here, "../dist/index.html"), "utf8")
  .replace("<title>Orochi</title>", "<title>Orochi — preview</title>")
  .replace(
    '<script type="module" src="app.js"></script>',
    '<script src="preview-data.js"></script>\n<script src="preview-files.js"></script>\n<script src="preview-channel.js"></script>\n<script src="preview-office.js"></script>\n<script type="module" src="app.js"></script>',
  );
writeFileSync(join(here, "../dist/preview.html"), markup);

// The Files pane answers by folder and by file, which one fixed answer per command cannot do.
// Built from the same recording the page's tests read, so what is looked at is what is tested.
const files = readFileSync(join(here, "files.json"), "utf8");
writeFileSync(
  join(here, "../dist/preview-files.js"),
  `// Generated by tests/make-preview.mjs from tests/files.json.
(() => {
  const files = ${files.trim()};
  const base = window.__TAURI__.core.invoke;
  const read = (path) =>
    path === "README.md" ? files.markdown : path === "blob.bin" ? files.binary : files.text;
  window.__TAURI__.core.invoke = (name, args = {}) => {
    if (name === "tree_refresh") return Promise.resolve(files.refresh);
    if (name === "tree_list") return Promise.resolve(files[args.dir === "" ? "root" : args.dir] ?? []);
    if (name === "tree_read") return Promise.resolve(read(args.path));
    if (name === "tree_find") return Promise.resolve(files[args.by] ?? []);
    if (name === "open_path") return Promise.resolve(null);
    return base(name, args);
  };
})();
`,
);
// The channel: a lead, two members (one continued across two seats), an assignment with its bar,
// an @you mention and an open trial, from the recording the tests read. `preview.html?thread`
// opens the first thread panel.
const channel = readFileSync(join(here, "channel.json"), "utf8");
writeFileSync(
  join(here, "../dist/preview-channel.js"),
  `// Generated by tests/make-preview.mjs from tests/channel.json.
(() => {
  const channel = ${channel.trim()};
  const base = window.__TAURI__.core.invoke;
  window.__TAURI__.core.invoke = (name, args = {}) =>
    name in channel ? Promise.resolve(channel[name]) : base(name, args);
  if (location.search.includes("thread")) {
    const open = () => {
      const bar = document.querySelector(".thread-bar");
      if (bar) bar.click(); else setTimeout(open, 200);
    };
    setTimeout(open, 400);
  }
})();
`,
);
console.log("preview.html built from index.html");

// The office, alive: three teams in two projects, one asking, agents who work and talk to each
// other — within a room and across rooms — on a loop, from `tests/office.json`. `preview.html?office`
// plays it (or a page that sets `window.__OFFICE_DEMO`); without that the other previews keep their
// own sidebar.
const office = readFileSync(join(here, "office.json"), "utf8");
writeFileSync(
  join(here, "../dist/preview-office.js"),
  `// Generated by tests/make-preview.mjs from tests/office.json.
(() => {
  if (!location.search.includes("office") && !window.__OFFICE_DEMO) return;
  const office = ${office.trim()};
  const base = window.__TAURI__.core.invoke;
  const born = Date.now();
  const clock = () => (Date.now() - born) / 1000;
  const spread = new Map(office.live_seats.map((s, i) => [s.seat_id, i * 2.3]));
  const seats = () => office.live_seats.map((s) => {
    const list = office.doings[s.seat_id] || [s.doing];
    const at = Math.floor((clock() + (spread.get(s.seat_id) || 0)) / 6) % list.length;
    return { ...s, doing: list[at], started_at: born - 60000 - (spread.get(s.seat_id) || 0) * 20000 };
  });
  // Someone finishes and leaves, a whole conversation ends, and both are back when the loop starts again.
  const sidebar = () => {
    const at = clock() % office.loop, view = structuredClone(office.sidebar);
    for (const project of view) for (const th of project.threads) {
      if (th.id === office.finish.reviewer.thread && at >= office.finish.reviewer.from) {
        for (const m of th.agents) if (m.role === "reviewer") m.live = 0;
      }
      if (th.id === office.finish.room.thread && at >= office.finish.room.from) {
        th.status = "unread";
        for (const m of th.agents) m.live = 0;
      }
    }
    return view;
  };
  const talk = () => {
    const now = clock(), turn = Math.floor(now / office.loop), at = now % office.loop, out = [];
    const owner = (id, role) => ({ id, role });
    office.script.forEach((step, i) => {
      for (const lap of [turn, turn - 1]) {
        const age = at - step.t + (turn - lap) * office.loop;
        if (age < 0 || age > 16) continue;
        out.push({
          seq: lap * 100 + i + 1, project_id: "p", via: "mailbox",
          from: step.from[1], from_thread: step.from[0], from_role: step.from[1],
          to: step.to[1], to_thread: step.to[0], to_role: step.to[1],
          text: step.text, mentions: step.mentions || [], at: Date.now() - age * 1000,
        });
      }
    });
    return out.sort((a, b) => b.at - a.at);
  };
  window.__TAURI__.core.invoke = (name, args = {}) => {
    if (name === "sidebar") return Promise.resolve(sidebar());
    if (name === "live_seats") {
      const at = clock() % office.loop;
      return Promise.resolve(seats().filter((s) => !(at >= office.finish.reviewer.from && s.seat_id === "c")
        && !(at >= office.finish.room.from && office.live_seats.find((x) => x.seat_id === s.seat_id)?.thread_id === office.finish.room.thread)));
    }
    if (name === "chatter") return Promise.resolve(talk());
    if (name === "room") return Promise.resolve([]);
    if (name === "changed") return Promise.resolve(Math.floor(clock() / 1.5) !== window.__lastTick ? ((window.__lastTick = Math.floor(clock() / 1.5)), ["t1"]) : []);
    return name in office ? Promise.resolve(office[name]) : base(name, args);
  };
})();
`,
);
