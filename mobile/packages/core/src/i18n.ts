export function t(key: string, lang: Lang = 'en'): string {
  if (lang === 'ja') return ja[key] ?? key;
  return key;
}

export const hasTranslation = (key: string) => key in ja;
export const translationKeys = () => Object.keys(ja);

export function plural(n: number, one: string, many: string, lang: Lang): string {
  if (lang === 'ja') return `${n}${t(n === 1 ? one : many, 'ja')}`;
  return `${n} ${n === 1 ? one : many}`;
}

export function detectLang(locale: string | null | undefined): Lang {
  return /^ja\b/i.test(locale ?? '') ? 'ja' : 'en';
}
